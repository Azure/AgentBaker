#!/bin/bash

Describe 'addMarinerNvidiaRepo'
    setup() {
        TEST_DIR=$(mktemp -d)
        eval "$(sed -n '/^addMarinerNvidiaRepo()/,/^}/p' './vhdbuilder/scripts/linux/mariner/tool_installs_mariner.sh' | sed "s|/etc/yum.repos.d|${TEST_DIR}|g")"
    }

    cleanup() {
        rm -rf "$TEST_DIR"
    }

    BeforeEach 'setup'
    AfterEach 'cleanup'

    Describe 'Azure Linux 3'
        Parameters
            x86_64
            aarch64
        End

        It "leaves architecture substitution to the package manager on $1"
            OS_VERSION=3.0
            basearch="$1"

            When call addMarinerNvidiaRepo

            The status should be success
            The contents of file "${TEST_DIR}/azurelinux-nvidia.repo" should include "name=Azure Linux Official Nvidia 3.0 \$basearch"
            The contents of file "${TEST_DIR}/azurelinux-nvidia.repo" should include "baseurl=https://packages.microsoft.com/azurelinux/3.0/prod/nvidia/\$basearch/"
            The contents of file "${TEST_DIR}/azurelinux-nvidia.repo" should include 'gpgcheck=1'
            The contents of file "${TEST_DIR}/azurelinux-nvidia.repo" should include 'repo_gpgcheck=1'
            The contents of file "${TEST_DIR}/azurelinux-nvidia.repo" should include 'sslverify=1'
            The path "${TEST_DIR}/mariner-nvidia.repo" should not be exist
        End
    End

    It 'preserves the Mariner 2 repository'
        OS_VERSION=2.0

        When call addMarinerNvidiaRepo

        The status should be success
        The contents of file "${TEST_DIR}/mariner-nvidia.repo" should include 'baseurl=https://packages.microsoft.com/cbl-mariner/2.0/prod/nvidia/x86_64'
        The path "${TEST_DIR}/azurelinux-nvidia.repo" should not be exist
    End
End
Describe 'removeOldAzureLinuxKernels'
    OLD_KERNEL=kernel-6.6.159.1-1.azl3.x86_64
    NEW_KERNEL=kernel-6.6.159.1-2.azl3.x86_64

    setup() {
        TEST_DIR=$(mktemp -d)
        BOOT_DIR="${TEST_DIR}/boot"
        mkdir -p "${BOOT_DIR}/grub2"
        echo kernel > "${BOOT_DIR}/vmlinuz-6.6.159.1-2.azl3"
        printf '%s\n' '# automatically generated by grub2-mkconfig' 'linux /vmlinuz-6.6.159.1-2.azl3' 'linux /vmlinuz-6.6.159.1-1.azl3' > "${BOOT_DIR}/grub2/grub.cfg"
        INSTALLED="${TEST_DIR}/installed"
        REMOVED="${TEST_DIR}/removed"
        touch "$REMOVED"
        printf '%s\n' "100 ${OLD_KERNEL} 6.6.159.1-1.azl3" "200 ${NEW_KERNEL} 6.6.159.1-2.azl3" > "$INSTALLED"
        RUNNING_OWNER="kernel ${NEW_KERNEL} 6.6.159.1-2.azl3"
        BLOCKED_REMOVAL=""
        BREAK_GRUB_ON_REMOVAL=false
        eval "$(sed -n '/^removeOldAzureLinuxKernels()/,/^}/p' './vhdbuilder/scripts/linux/mariner/tool_installs_mariner.sh')"
    }

    cleanup() {
        rm -rf "$TEST_DIR"
    }

    uname() {
        echo "6.6.159.1-2.azl3"
    }

    grub2-script-check() {
        [ -s "$1" ]
    }

    # Simulates rpm, including the kernel %postun GRUB regeneration.
    rpm() {
        case "$1" in
            -qf)
                if [ -z "$RUNNING_OWNER" ]; then echo "file $4 is not owned by any package"; return 1; fi
                echo "$RUNNING_OWNER" ;;
            -q)
                if [ "$2" = "--queryformat" ]; then cat "$INSTALLED"; else grep -qF " $2 " "$INSTALLED"; fi ;;
            -e)
                if [ "$2" = "--test" ]; then
                    [ "$3" != "$BLOCKED_REMOVAL" ] || { echo "$3 is needed by kernel-uki"; return 1; }
                    return 0
                fi
                echo "$2" >> "$REMOVED"
                grep -vF " $2 " "$INSTALLED" > "${INSTALLED}.tmp"; mv "${INSTALLED}.tmp" "$INSTALLED"
                if [ "$BREAK_GRUB_ON_REMOVAL" = true ]; then
                    : > "${BOOT_DIR}/grub2/grub.cfg"
                elif grep -q "automatically generated by grub2-mkconfig" "${BOOT_DIR}/grub2/grub.cfg"; then
                    sed -i '/vmlinuz-6.6.159.1-1.azl3/d' "${BOOT_DIR}/grub2/grub.cfg"
                fi ;;
        esac
    }

    BeforeEach 'setup'
    AfterEach 'cleanup'

    It 'removes only the superseded kernel package and validates GRUB'
        When call removeOldAzureLinuxKernels
        The status should be success
        The output should include "Removing superseded kernel ${OLD_KERNEL}"
        The contents of file "$REMOVED" should equal "$OLD_KERNEL"
        The contents of file "$INSTALLED" should equal "200 ${NEW_KERNEL} 6.6.159.1-2.azl3"
    End

    It 'skips images that boot a different kernel package such as Kata kernel-mshv'
        RUNNING_OWNER="kernel-mshv kernel-mshv-6.6.100-1.azl3.x86_64 6.6.100-1.azl3"
        When call removeOldAzureLinuxKernels
        The status should be success
        The output should include "not owned by the 'kernel' package"
        The contents of file "$REMOVED" should equal ''
    End

    It 'skips when the running kernel file is not owned by any package'
        RUNNING_OWNER=""
        When call removeOldAzureLinuxKernels
        The status should be success
        The output should include '(unowned)'
        The contents of file "$REMOVED" should equal ''
    End

    It 'skips when the running kernel is not the newest installed kernel'
        RUNNING_OWNER="kernel ${OLD_KERNEL} 6.6.159.1-1.azl3"
        When call removeOldAzureLinuxKernels
        The status should be success
        The output should include 'is not the only newest installed kernel'
        The contents of file "$REMOVED" should equal ''
    End

    It 'skips when another kernel has the same install time'
        printf '%s\n' "200 ${OLD_KERNEL} 6.6.159.1-1.azl3" "200 ${NEW_KERNEL} 6.6.159.1-2.azl3" > "$INSTALLED"
        When call removeOldAzureLinuxKernels
        The status should be success
        The output should include 'is not the only newest installed kernel'
        The contents of file "$REMOVED" should equal ''
    End

    It 'keeps an old kernel that another package depends on'
        BLOCKED_REMOVAL="$OLD_KERNEL"
        When call removeOldAzureLinuxKernels
        The status should be success
        The output should include "Keeping ${OLD_KERNEL} because other packages depend on it"
        The contents of file "$REMOVED" should equal ''
    End

    It 'keeps an old kernel referenced by a GRUB config not generated by grub2-mkconfig'
        printf '%s\n' 'linux /vmlinuz-6.6.159.1-2.azl3' 'linux /vmlinuz-6.6.159.1-1.azl3' > "${BOOT_DIR}/grub2/grub.cfg"
        When call removeOldAzureLinuxKernels
        The status should be success
        The output should include "Keeping ${OLD_KERNEL} because ${BOOT_DIR}/grub2/grub.cfg references it"
        The contents of file "$REMOVED" should equal ''
    End

    It 'fails when GRUB regeneration loses the running kernel'
        BREAK_GRUB_ON_REMOVAL=true
        When call removeOldAzureLinuxKernels
        The status should be failure
        The output should include "Removing superseded kernel ${OLD_KERNEL}"
        The error should include 'no longer references running kernel 6.6.159.1-2.azl3'
    End
End
