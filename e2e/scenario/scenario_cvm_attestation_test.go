func startCVMCommandSSHServer(t *testing.T, signer ssh.Signer, run func(*ssh.ServerConn, ssh.Channel, string)) (string, <-chan string, <-chan struct{}) {
	t.Helper()
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	require.NoError(t, err)
	t.Cleanup(func() { _ = listener.Close() })
	commands := make(chan string, 16)
	serverDone := make(chan struct{})
	go func() {
		defer close(serverDone)
		conn, acceptErr := listener.Accept()
		if acceptErr != nil {
			return
		}
		defer conn.Close()
		serverConfig := &ssh.ServerConfig{NoClientAuth: true}
		serverConfig.AddHostKey(signer)
		server, channels, requests, handshakeErr := ssh.NewServerConn(conn, serverConfig)
		if handshakeErr != nil {
			return
		}
		defer server.Close()
		go ssh.DiscardRequests(requests)
		for incoming := range channels {
			channel, channelRequests, channelErr := incoming.Accept()
			if channelErr != nil {
				return
			}
			for request := range channelRequests {
				var command struct{ Command string }
				if request.Type != "exec" || ssh.Unmarshal(request.Payload, &command) != nil {
					_ = request.Reply(false, nil)
					continue
				}
				commands <- command.Command
				_ = request.Reply(true, nil)
				run(server, channel, command.Command)
				break
			}
		}
	}()
	return listener.Addr().String(), commands, serverDone
}

