func TestVerifyCVMAttestationToken(t *testing.T) {
	for _, platform := range []cvmPlatform{cvmPlatformSEVSNP, cvmPlatformTDX} {
		t.Run(string(platform), func(t *testing.T) {
			privateKey, certificate := newTestSigningCertificate(t)
			const keyID = "test-key"
			var issuer string
			server := httptest.NewTLSServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				switch r.URL.Path {
				case "/.well-known/openid-configuration":
					if r.URL.Query().Get("api-version") != "2025-06-01" {
						http.Error(w, "unexpected API version", http.StatusBadRequest)
						return
					}
					_ = json.NewEncoder(w).Encode(map[string]any{
						"issuer":                                issuer,
						"jwks_uri":                              issuer + "/certs",
						"id_token_signing_alg_values_supported": []string{"RS256"},
					})
				case "/certs":
					_ = json.NewEncoder(w).Encode(map[string]any{
						"keys": []map[string]any{{
							"kid": keyID,
							"kty": "RSA",
							"x5c": []string{base64.StdEncoding.EncodeToString(certificate.Raw)},
						}},
					})
				default:
					http.NotFound(w, r)
				}
			}))
			defer server.Close()
			issuer = server.URL

			nonce := "0123456789abcdef"
			claims := validCVMAttestationClaims(platform, issuer, nonce)
			token := jwt.NewWithClaims(jwt.SigningMethodRS256, claims)
			token.Header["kid"] = keyID
			token.Header["jku"] = issuer + "/certs"
			encodedToken, err := token.SignedString(privateKey)
			require.NoError(t, err)

			summary, err := verifyCVMAttestationToken(
				context.Background(),
				server.Client(),
				encodedToken,
				issuer,
				platform,
				nonce,
			)
			require.NoError(t, err)
			assert.Equal(t, platform, summary.Platform)
			assert.Equal(t, issuer, summary.Issuer)
			assert.Equal(t, "azure-compliant-cvm", summary.ComplianceStatus)
			assert.Equal(t, cvmNonceDigest(nonce), summary.UserDataDigest)
			assert.NotEmpty(t, summary.PolicyClaims)
		})
	}
}

func TestCVMAttestationCollectorTimeout(t *testing.T) {
	script := cvmAttestationCollectorScript(cvmPlatformSEVSNP, "nonce", "/tmp/test")
	var timeoutArgs []string
	for _, line := range strings.Split(script, "\n") {
		if strings.HasPrefix(line, "sudo timeout ") {
			timeoutArgs = strings.Fields(strings.SplitN(line, " env ", 2)[0])[2:]
			break
		}
	}
	require.Equal(t, []string{"--verbose", "--signal=TERM", "--kill-after=10s", "180s"}, timeoutArgs)
	if _, err := exec.LookPath("timeout"); err != nil {
		t.Skip("GNU timeout is not installed")
	}

	timeoutArgs[len(timeoutArgs)-1] = "0.1s"
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	command := exec.CommandContext(ctx, "timeout", append(timeoutArgs, "sh", "-c", "sleep 30")...)
	output, err := command.CombinedOutput()
	require.NoError(t, ctx.Err(), "collector timeout did not terminate the stalled command")
	var exitErr *exec.ExitError
	require.ErrorAs(t, err, &exitErr)
	assert.Equal(t, 124, exitErr.ExitCode())
	assert.Contains(t, string(output), "sending signal TERM")
}

func TestBoundedWriterRejectsOversizedRemoteFile(t *testing.T) {
	var output strings.Builder
	writer := &boundedWriter{writer: &output, remaining: 4}

	n, err := writer.Write([]byte("four"))
	require.NoError(t, err)
	assert.Equal(t, 4, n)
	assert.Equal(t, "four", output.String())

	n, err = writer.Write([]byte("!"))
	require.ErrorContains(t, err, "exceeds maximum size")
	assert.Zero(t, n)
	assert.Equal(t, "four", output.String())
}

func TestValidateCVMAttestationClaimsRejectsWrongNonceAndPlatform(t *testing.T) {
	claims := validCVMAttestationClaims(cvmPlatformSEVSNP, cvmAttestationIssuer, "expected")

	_, err := validateCVMAttestationClaims(claims, cvmPlatformSEVSNP, "wrong")
	require.ErrorContains(t, err, "does not match")

	_, err = validateCVMAttestationClaims(claims, cvmPlatformTDX, "expected")
	require.ErrorContains(t, err, "expected attestation type")
}

func validCVMAttestationClaims(platform cvmPlatform, issuer, nonce string) jwt.MapClaims {
	now := time.Now()
	claims := jwt.MapClaims{
		"iss":                    issuer,
		"iat":                    now.Unix(),
		"nbf":                    now.Add(-time.Minute).Unix(),
		"exp":                    now.Add(time.Hour).Unix(),
		"x-ms-compliance-status": "azure-compliant-cvm",
		"x-ms-runtime": map[string]any{
			"user-data": strings.ToLower(cvmNonceDigest(nonce)),
			"vm-configuration": map[string]any{
				"secure-boot": true,
				"tpm-enabled": true,
			},
		},
	}
	if platform == cvmPlatformTDX {
		claims["x-ms-attestation-type"] = "tdxvm"
		claims["attester_tcb_status"] = "UpToDate"
		claims["dbgstat"] = "disabled"
		claims["tdx_td_attributes_debug"] = false
		for _, claim := range []string{
			"tdx_tee_tcb_svn",
			"tdx_mrseam",
			"tdx_mrtd",
			"tdx_report_data",
			"tdx_rtmr0",
			"tdx_rtmr1",
			"tdx_rtmr2",
			"tdx_rtmr3",
		} {
			claims[claim] = "test-value"
		}
	} else {
		claims["x-ms-attestation-type"] = "sevsnpvm"
		claims["x-ms-sevsnpvm-is-debuggable"] = false
		claims["x-ms-sevsnpvm-vmpl"] = 0
		claims["x-ms-sevsnpvm-migration-allowed"] = false
		claims["x-ms-sevsnpvm-smt-allowed"] = true
		for _, claim := range []string{
			"x-ms-sevsnpvm-bootloader-svn",
			"x-ms-sevsnpvm-guestsvn",
			"x-ms-sevsnpvm-microcode-svn",
			"x-ms-sevsnpvm-snpfw-svn",
			"x-ms-sevsnpvm-tee-svn",
		} {
			claims[claim] = 1
		}
		claims["x-ms-sevsnpvm-launchmeasurement"] = "test-measurement"
		claims["x-ms-sevsnpvm-reportdata"] = "test-report-data"
	}
	return claims
}

func newTestSigningCertificate(t *testing.T) (*rsa.PrivateKey, *x509.Certificate) {
	t.Helper()
	privateKey, err := rsa.GenerateKey(rand.Reader, 2048)
	require.NoError(t, err)
	template := &x509.Certificate{
		SerialNumber: big.NewInt(1),
		Subject:      pkix.Name{CommonName: "test MAA signer"},
		NotBefore:    time.Now().Add(-time.Hour),
		NotAfter:     time.Now().Add(time.Hour),
		KeyUsage:     x509.KeyUsageDigitalSignature,
	}
	certificateDER, err := x509.CreateCertificate(rand.Reader, template, template, &privateKey.PublicKey, privateKey)
	require.NoError(t, err)
	certificate, err := x509.ParseCertificate(certificateDER)
	require.NoError(t, err)
	return privateKey, certificate
}
