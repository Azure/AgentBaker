#!/usr/bin/env python3
"""
Combined ANC hotfix generator.

Auto-detects what needs a hotfix and generates the version numbers for it:

1. If aks-node-controller/ (the Go module) has changes other than *_test.go or
   testdata files vs the base branch, bumps the patch of the current
   pkg/agent/datamodel/linux_sig_version.json version and uses it as `version`.

2. Detects which CSE provisioning scripts changed vs the base branch, injects their
   write_files entries into the EnableScriptlessCSECmd section of
   parts/linux/cloud-init/nodecustomdata.yml, and generates a matching ANC-owned
   embedded payload. If that injection (or a direct edit) leaves nodecustomdata.yml
   different from the base branch, `scripts_version` is bumped using the same
   base-version + tag-collision algorithm as `version`.

3. Writes the resulting {"version", "scripts_version"} (omitting fields that don't
   apply) to parts/linux/cloud-init/artifacts/aks-node-controller-hotfix.json only
   when there is an active hotfix. If no hotfix applies, the file is removed/left
   absent so scriptless customData does not embed an empty hotfix artifact.

Usage: python3 hotfix/hotfix_generate.py [--embedded-only] <base_ref>
  base_ref: git ref to diff against for changed-script/changed-code detection
            (e.g., origin/official/v20260219)
  --embedded-only: omit the legacy CRP script block. This is intentionally
                   default-off until 15 supported-version rotations complete
                   and the oldest supported ABSvc/VHD release is confirmed
                   embedded-capable.

This script is called by the hotfix-generate GH Action.
"""

